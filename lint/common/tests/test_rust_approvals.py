from __future__ import annotations

import unittest

from lint.common.tests.test_style_check import APPROVED, RepoCase, lines

LINTS = "clippy::ref_as_ptr clippy::inline_always"
EXPECT = '#[expect(clippy::ref_as_ptr, clippy::inline_always, reason = "generated by the windows-implement macro")]'
ESCAPED = EXPECT.replace('"', '\\"')
SUPPRESSION = "lint suppression (GEN-4)"


def module(attribute: str) -> str:
    return lines("mod listener {", f"    {attribute}", "    pub struct Listener;", "}")


def stale(path: str, lints: str = "clippy::ref_as_ptr, clippy::inline_always") -> str:
    return f"{APPROVED}:1: {path} has no expect({lints}) left; remove this line (GEN-4)"


class RustApprovalTests(RepoCase):
    def assert_unapproved(self, *, has_comment: bool = False) -> None:
        comment = ["src/win/devices.rs:2: comment (GEN-29)"] if has_comment else []
        self.assert_findings([stale("src/win/devices.rs"), *comment, f"src/win/devices.rs:2: {SUPPRESSION}"])

    def test_approved_expect_passes(self) -> None:
        self.write("src/win/devices.rs", module(EXPECT))
        self.write(
            "src/win/process.rs",
            module('#[expect(clippy::inline_always, clippy::ref_as_ptr, reason = "generated")]'),
        )
        self.write(
            APPROVED,
            lines(f"/src/win/devices.rs {LINTS}", "/src/win/process.rs clippy::ref_as_ptr clippy::inline_always"),
        )
        self.assert_clean()

    def test_unapproved_expect_fails(self) -> None:
        self.write("src/win/devices.rs", module(EXPECT) + module(EXPECT))
        self.write("src/win/other.rs", module('#[expect(clippy::unwrap_used, reason = "x")]'))
        self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
        self.assert_findings([f"src/win/devices.rs:6: {SUPPRESSION}", f"src/win/other.rs:2: {SUPPRESSION}"])

    def test_allow_fails_even_when_listed(self) -> None:
        self.write(
            "src/win/devices.rs",
            module('#[allow(clippy::ref_as_ptr, clippy::inline_always, reason = "generated")]'),
        )
        self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
        self.assert_unapproved()

    def test_extra_or_missing_lint_fails(self) -> None:
        for attribute in (
            '#[expect(clippy::ref_as_ptr, clippy::inline_always, clippy::unwrap_used, reason = "generated")]',
            '#[expect(clippy::ref_as_ptr, reason = "generated")]',
            '#[expect(clippy::all, reason = "generated")]',
        ):
            with self.subTest(attribute=attribute):
                self.write("src/win/devices.rs", module(attribute))
                self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
                self.assert_unapproved()

    def test_right_lints_in_the_wrong_file_fail(self) -> None:
        self.write("src/win/devices.rs", module(EXPECT))
        self.write("src/win/process.rs", lines("pub struct Process;"))
        self.write(APPROVED, lines(f"/src/win/process.rs {LINTS}"))
        self.assert_findings([stale("src/win/process.rs"), f"src/win/devices.rs:2: {SUPPRESSION}"])

    def test_expect_without_a_reason_fails(self) -> None:
        for attribute in (
            "#[expect(clippy::ref_as_ptr, clippy::inline_always)]",
            '#[expect(clippy::ref_as_ptr, clippy::inline_always, reason = "")]',
            '#[expect(clippy::ref_as_ptr, clippy::inline_always, reason = "  ")]',
            "#[expect(clippy::ref_as_ptr, clippy::inline_always, reason = REASON)]",
            "#[expect(clippy::ref_as_ptr, clippy::inline_always, reason = /* why */)]",
        ):
            with self.subTest(attribute=attribute):
                self.write("src/win/devices.rs", module(attribute))
                self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
                self.assert_unapproved(has_comment="/*" in attribute)

    def test_multiline_expect_passes(self) -> None:
        self.write(
            "src/win/devices.rs",
            lines(
                "mod listener {",
                "    #[expect(",
                "        clippy::ref_as_ptr,",
                "        clippy::inline_always,",
                '        reason = r#"generated by the "windows-implement" macro"#,',
                "    )]",
                "    pub struct Listener;",
                "}",
            ),
        )
        self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
        self.assert_clean()

    def test_text_outside_the_attribute_does_not_approve(self) -> None:
        unwrap = '#[expect(clippy::unwrap_used, reason = "x")]'
        for line in (
            f"{unwrap} // {EXPECT}",
            f'{unwrap} const A: &str = "{ESCAPED}";',
            '#[expect(clippy::unwrap_used /* clippy::ref_as_ptr, clippy::inline_always */, reason = "x")]',
            '#[expect(clippy::unwrap_used, reason = "clippy::ref_as_ptr, clippy::inline_always")]',
            '#[cfg_attr(windows, expect(clippy::ref_as_ptr, clippy::inline_always, reason = "generated"))]',
            '#![expect(clippy::ref_as_ptr, clippy::inline_always, reason = "generated")]',
            '#[expect(clippy::ref_as_ptr, clippy::inline_always, reason = "generated"), unknown]',
        ):
            with self.subTest(line=line):
                self.write("src/win/devices.rs", module(line))
                self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
                self.assert_unapproved(has_comment="//" in line or "/*" in line)

    def test_one_approval_lets_one_of_two_attributes_on_a_line_through(self) -> None:
        self.write("src/win/devices.rs", module(f'{EXPECT} #[expect(clippy::unwrap_used, reason = "x")]'))
        self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
        self.assert_findings([f"src/win/devices.rs:2: {SUPPRESSION}"])

    def test_stale_rust_approval_is_a_finding(self) -> None:
        self.write("src/win/devices.rs", lines("pub struct Listener;"))
        self.write(APPROVED, lines(f"/src/win/devices.rs {LINTS}"))
        self.assert_findings([stale("src/win/devices.rs")])

    def test_bad_rust_entry_is_a_setup_error(self) -> None:
        self.write("src/win/devices.rs", module(EXPECT))
        self.write("src/Db.cs", lines("class A { }"))
        for entry in (
            "/src/win/devices.rs",
            "/src/win/devices.rs clippy::pedantic",
            "/src/win/devices.rs warnings",
            "/src/win/devices.rs clippy",
            "/src/win/devices.rs clippy::ref_as_ptr clippy::ref_as_ptr",
            "/src/win/devices.rs Clippy::Ref_As_Ptr",
            "/src/Db.cs CA2100 CA1031",
            "/src/Db.cs clippy::ref_as_ptr",
        ):
            with self.subTest(entry=entry):
                self.write(APPROVED, lines(entry))
                self.assertEqual(self.run_check().code, 2)


if __name__ == "__main__":
    _ = unittest.main()
